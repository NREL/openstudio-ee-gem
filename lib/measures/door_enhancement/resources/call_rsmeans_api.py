def main() -> int:
    """Main entry point when run as a standalone script."""
    args = parse_args()
    load_dotenv()

    client_id = os.getenv("client_id")
    client_secret = os.getenv("client_secret")

    if not client_id or not client_secret:
        print("ERROR: RSMeans API credentials not found.")
        print("Set environment variables: client_id, client_secret")
        print("Or create a .env file with these values.")
        return 1

    model_path = Path(args.model).resolve()
    if not model_path.exists():
        print(f"ERROR: Model file not found: {model_path}")
        return 1

    # Try multiple methods to extract materials
    materials = None
    model_dir = model_path.parent
    
    # Method 1: Pre-saved JSON file
    materials_file_candidates = [
        model_dir / "door_enhancement_retrofit_materials.json",
    ]
    for materials_file in materials_file_candidates:
        if materials_file.exists():
            try:
                with open(materials_file, "r", encoding="utf-8") as f:
                    materials = json.load(f)
                print(f"Extracted {len(materials)} materials from {materials_file.name}")
                break
            except Exception as e:
                print(f"Warning: Could not load materials file {materials_file.name}: {e}")
    
    # Method 2: Extract from model's Facility AdditionalProperties
    if not materials:
        print(f"Loading model from {model_path.name}...")
        model = load_openstudio_model(model_path)
        
        if model.facility().is_initialized():
            facility = model.facility().get()
            props = facility.additionalProperties()
            
            # Try door-specific serialized materials property.
            facility_json_feature_candidates = [
                "door_enhancement_retrofit_materials_json",
            ]
            for feature_name in facility_json_feature_candidates:
                if materials:
                    break
                if props.hasFeature(feature_name):
                    try:
                        opt_str = props.getFeatureAsString(feature_name)
                        if opt_str.is_initialized():
                            json_str = opt_str.get()
                            materials = json.loads(json_str)
                            print(f"Extracted {len(materials)} materials from Facility.{feature_name}")
                            break
                    except Exception as e:
                        print(f"Warning: Could not parse Facility.{feature_name}: {e}")
        
        # Method 3: Fall back to individual property extraction
        if not materials:
            materials = extract_materials_from_model(model, DEFAULT_FEATURE_KEYS)
            if materials:
                print(f"Extracted {len(materials)} materials using standard property keys")

        # Method 4: Derive a door-based search term from the model
        if not materials:
            derived = build_door_search_material_from_model(model)
            if derived:
                materials = [derived]
                print("Derived door-based RSMeans search term from model:")
                print(f"  Search term: {derived['name']}")
                print(f"  Details: {derived['description']}")

    if not materials:
        print("ERROR: No retrofit materials found in model.")
        print("The model must have materials stored in AdditionalProperties.")
        return 1

    # Parse catalog list
    catalogs = [c.strip() for c in args.catalogs.split(",")]
    print(f"\nSearching RSMeans catalogs: {', '.join(catalogs)}")
    
    # Authenticate
    client = RSMeansAPIClient(client_id, client_secret, use_sandbox=args.use_sandbox)
    if not client.authenticate():
        print("ERROR: Authentication failed.")
        return 1

    # Search across all catalogs
    print(f"Searching for {len(materials)} materials...")
    results = search_materials_across_catalogs(
        materials=materials,
        client=client,
        catalogs=catalogs,
        release_id=args.release,
        location_id=args.location,
        labor_type=args.labor_type,
        measurement_system=args.measurement_system,
    )

    # Calculate costs
    total_material_cost = float(results.get("total_cost", 0.0))
    # Per-line unit costs already include RSMeans O&P (``totalOpCost``); no
    # additional markup is applied.
    overhead_profit_cost = 0.0
    total_cost = total_material_cost

    # Prepare summary
    summary = {
        "total_material_cost": total_material_cost,
        "overhead_profit_percent": args.overhead_profit_percent,
        "total_overhead_profit_cost": overhead_profit_cost,
        "total_cost_with_overhead_profit": total_cost,
        "materials_count": len(results.get("materials", [])),
        "materials_searched": len(materials),
        "catalogs_searched": catalogs,
    }

    # Save results
    output_path = Path(args.output).resolve()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8") as f:
        json.dump({"summary": summary, "results": results}, f, indent=2)

    # Print summary
    print("\n" + "=" * 70)
    print("COST SUMMARY")
    print("=" * 70)
    print(f"Materials searched:  {len(materials)}")
    print(f"Materials matched:   {len(results.get('materials', []))}")
    print(f"Material cost:       ${total_material_cost:,.2f}")
    print(f"Overhead+profit:     ${overhead_profit_cost:,.2f} ({args.overhead_profit_percent}%)")
    print(f"TOTAL COST:          ${total_cost:,.2f}")
    print("=" * 70)
    
    if results.get("errors"):
        print(f"\nWarnings ({len(results['errors'])} items):")
        for error in results["errors"][:5]:
            print(f"  - {error}")
        if len(results["errors"]) > 5:
            print(f"  ... and {len(results['errors']) - 5} more")
    
    print(f"\nResults saved to: {output_path}")
    return 0


def search_materials_across_catalogs(
    materials: List[Dict[str, Any]],
    client: "RSMeansAPIClient",
    catalogs: Optional[List[str]] = None,
    release_id: str = "2024-an",
    location_id: str = "us-us-national",
    labor_type: str = "std",
    measurement_system: str = "imp",
) -> Dict[str, Any]:
    """Search for materials across multiple RSMeans catalogs and return best matches.

    For each material the function tries, in order:
    1. Exact user-supplied RSMeans ID (if ``explicit_rsmeans_id`` is set).
    2. Text search using ``generate_search_term_alternatives``, accepting the
       first candidate whose clamped score >= ``MIN_ACCEPTABLE_MATCH_SCORE``.
    3. Hard-coded fallback ID from ``_get_default_fallback_rsmeans_id`` if no
       search result passes the score threshold.
    
    Args:
        materials: List of material dicts with 'name', 'quantity', 'unit', etc.
        client: Authenticated RSMeansAPIClient instance
        catalogs: List of catalog codes to search (default: all common catalogs)
        release_id: RSMeans release ID (e.g., "2024-an")
        location_id: Location for pricing
        labor_type: Labor type code
        measurement_system: "imp" or "met"
    
    Returns:
        Dict with 'total_cost', 'materials' (with catalog info), 'errors', 'search_log'
    """
    if catalogs is None:
        # Default to common building-related catalogs
        catalogs = ["bc-mf", "gb-mf", "rp-mf"]  # Building Construction, Green Building, Repair & Remodeling
    
    all_results = []
    search_log = []
    errors = []
    warnings = []
    total_cost = 0.0
    total_material_cost_bare = 0.0
    total_labor_cost_bare = 0.0
    total_equipment_cost_bare = 0.0
    fallback_count = 0
    
    for material in materials:
        material_name = material.get("name", "unknown")
        quantity = material.get("quantity", 1.0)
        unit = material.get("unit", "")
        division_code = material.get("division_code")
        explicit_rsmeans_id = str(
            material.get("explicit_rsmeans_id")
            or material.get("rsmeans_unit_costline_id")
            or ""
        ).strip()

        print("\n" + "-" * 70)
        print(f"RSMeans lookup for material: {material_name}")
        print(f"Quantity: {quantity} {unit} | Division: {division_code or 'auto'}")
        
        best_match = None
        best_cost = None
        best_catalog = None
        matched_term = None
        best_source = "rsmeans_search"

        # Optional exact line-id override path (if user supplied one).
        if explicit_rsmeans_id:
            for catalog in catalogs:
                explicit_item = _lookup_cost_item_by_rsmeans_id(
                    client=client,
                    rsmeans_id=explicit_rsmeans_id,
                    catalog=catalog,
                    release_id=release_id,
                    location_id=location_id,
                    labor_type=labor_type,
                    measurement_system=measurement_system,
                )
                if explicit_item:
                    unit_cost = float(explicit_item.get("localizedCosts", {}).get("totalOpCost", 0.0) or 0.0)
                    line_uom = explicit_item.get("unitOfMeasure", "")
                    line_id = explicit_item.get("id", explicit_rsmeans_id)
                    if unit_cost > 0 and division_code and not _id_matches_division(line_id, division_code):
                        warnings.append(
                            f"User-provided RSMeans ID {explicit_rsmeans_id} for '{material_name}' "
                            f"resolved to id '{line_id}' which is outside requested division '{division_code}'. "
                            f"Rejecting to avoid cross-division contamination."
                        )
                        unit_cost = 0.0
                    if unit_cost > 0 and not _uom_compatible(unit, line_uom):
                        warnings.append(
                            f"User-provided RSMeans ID {explicit_rsmeans_id} for '{material_name}' "
                            f"has UOM '{line_uom}' which is incompatible with requested unit '{unit}'. "
                            f"Rejecting this match to avoid unit-mismatch costing errors."
                        )
                        unit_cost = 0.0
                    if unit_cost > 0:
                        total = unit_cost * quantity
                        _split = _split_total_by_bare(explicit_item, total)
                        all_results.append({
                            **material,
                            "catalog": catalog,
                            "search_term_used": "user_rsmeans_id",
                            "unit_cost": unit_cost,
                            "total_cost": total,
                            "total_material_cost": _split["material"],
                            "total_labor_cost": _split["labor"],
                            "total_equipment_cost": _split["equipment"],
                            "bare_material_unit_cost": (float(_split["material"] or 0.0) / float(quantity or 1.0)) if float(quantity or 0.0) > 0.0 else 0.0,
                            "bare_material_unit_basis": line_uom,
                            "cost_component_source": _split["source"],
                            "rsmeans_id": explicit_item.get("id", explicit_rsmeans_id),
                            "rsmeans_description": explicit_item.get("description", ""),
                            "rsmeans_unit_of_measure": line_uom,
                            "source": "rsmeans_user_id",
                            "match_type": "exact_id_match",
                            "chosen_source_type": "user_id",
                        })
                        _append_rsmeans_raw_log(material, explicit_item, catalog, "explicit_id_match", "user_rsmeans_id")
                        total_cost += total
                        total_material_cost_bare += _split["material"]
                        total_labor_cost_bare += _split["labor"]
                        total_equipment_cost_bare += _split["equipment"]
                        search_log.append({
                            "material": material_name,
                            "status": "explicit_id_match",
                            "explicit_rsmeans_id": explicit_rsmeans_id,
                            "catalog": catalog,
                            "unit_cost": unit_cost,
                            "unit_of_measure": line_uom,
                            "quantity": quantity,
                            "total_cost": total,
                        })
                        best_match = explicit_item
                        break

            if best_match:
                continue

            warnings.append(
                f"User-provided RSMeans ID {explicit_rsmeans_id} was not found; falling back to search logic for '{material_name}'"
            )

        # Forced fallback path for configured seal/door options.
        forced_fallback_id = _get_forced_fallback_rsmeans_id(
            material_name,
            material.get("description", ""),
        )
        if forced_fallback_id:
            forced_item = None
            forced_catalog = None
            for catalog in catalogs:
                forced_item = _lookup_cost_item_by_rsmeans_id(
                    client=client,
                    rsmeans_id=forced_fallback_id,
                    catalog=catalog,
                    release_id=release_id,
                    location_id=location_id,
                    labor_type=labor_type,
                    measurement_system=measurement_system,
                )
                if forced_item:
                    forced_catalog = catalog
                    break

            if forced_item:
                unit_cost = float(forced_item.get("localizedCosts", {}).get("totalOpCost", 0.0) or 0.0)
                line_uom = forced_item.get("unitOfMeasure", "")
                line_id = forced_item.get("id", forced_fallback_id)
                if unit_cost > 0 and division_code and not _id_matches_division(line_id, division_code):
                    warnings.append(
                        f"Forced RSMeans ID {forced_fallback_id} for '{material_name}' "
                        f"resolved to id '{line_id}' outside division '{division_code}'. "
                        f"Falling back to search logic."
                    )
                    unit_cost = 0.0
                if unit_cost > 0 and not _uom_compatible(unit, line_uom):
                    warnings.append(
                        f"Forced RSMeans ID {forced_fallback_id} for '{material_name}' "
                        f"has UOM '{line_uom}' incompatible with requested unit '{unit}'. "
                        f"Falling back to search logic."
                    )
                    unit_cost = 0.0

                if unit_cost > 0:
                    total = unit_cost * quantity
                    _split = _split_total_by_bare(forced_item, total)
                    all_results.append({
                        **material,
                        "catalog": forced_catalog,
                        "search_term_used": "forced_fallback_rsmeans_id",
                        "unit_cost": unit_cost,
                        "total_cost": total,
                        "total_material_cost": _split["material"],
                        "total_labor_cost": _split["labor"],
                        "total_equipment_cost": _split["equipment"],
                        "bare_material_unit_cost": (float(_split["material"] or 0.0) / float(quantity or 1.0)) if float(quantity or 0.0) > 0.0 else 0.0,
                        "bare_material_unit_basis": line_uom,
                        "cost_component_source": _split["source"],
                        "rsmeans_id": line_id,
                        "rsmeans_description": forced_item.get("description", ""),
                        "rsmeans_unit_of_measure": line_uom,
                        "source": "rsmeans_forced_fallback_id",
                        "match_type": "forced_fallback_id",
                        "chosen_source_type": "forced_fallback",
                    })
                    _append_rsmeans_raw_log(
                        material,
                        forced_item,
                        forced_catalog,
                        "forced_fallback_rsmeans_id",
                        "forced_fallback_rsmeans_id",
                    )
                    total_cost += total
                    total_material_cost_bare += _split["material"]
                    total_labor_cost_bare += _split["labor"]
                    total_equipment_cost_bare += _split["equipment"]
                    fallback_count += 1
                    search_log.append({
                        "material": material_name,
                        "status": "forced_fallback_match",
                        "forced_rsmeans_id": forced_fallback_id,
                        "catalog": forced_catalog,
                        "unit_cost": unit_cost,
                        "unit_of_measure": line_uom,
                        "quantity": quantity,
                        "total_cost": total,
                    })
                    continue
                warnings.append(
                    f"Forced RSMeans ID {forced_fallback_id} for '{material_name}' was found but unusable; falling back to search logic."
                )
            else:
                warnings.append(
                    f"Forced RSMeans ID {forced_fallback_id} for '{material_name}' was not found; falling back to search logic."
                )
        
        # Generate alternative search terms
        search_alternatives = generate_search_term_alternatives(material_name)
        
        # If we have a division code from material properties, prioritize it
        if division_code:
            search_alternatives.insert(0, (material_name, division_code))
        
        # Try each catalog with intelligent search term alternatives
        for catalog in catalogs:
            if best_match:
                break  # Already found a match in a previous catalog
            
            # Try alternative search terms within this catalog
            for alt_term, alt_division in search_alternatives:
                try:
                    print(f"  • Searching '{alt_term}' (div {alt_division or 'any'}) in {catalog}")
                    results = client.search_unit_costlines(
                        search_term=alt_term,
                        division_code=alt_division,
                        catalog=catalog,
                        release_id=release_id,
                        location_id=location_id,
                        labor_type=labor_type,
                        measurement_system=measurement_system,
                    )
                    
                    items = _filter_demo_items(_extract_search_items(results))
                    if items:
                        match, ranked_candidates = _select_best_rsmeans_candidate(
                            material_name,
                            items,
                            material,
                        )
                        if not match:
                            continue
                        division_id = match.get("id", "")
                        _candidate_count = len(ranked_candidates or [])
                        _force_fallback_multi = False
                        if not explicit_rsmeans_id and _candidate_count > 1:
                            _fallback_id = _get_default_fallback_rsmeans_id(
                                material_name,
                                material.get("description", ""),
                            )
                            if _fallback_id:
                                division_id = _fallback_id
                                _force_fallback_multi = True
                                search_log.append({
                                    "material": material_name,
                                    "search_term": alt_term,
                                    "catalog": catalog,
                                    "division": alt_division,
                                    "status": "multi_candidate_fallback",
                                    "forced_fallback_costline_id": division_id,
                                    "candidate_scores": ranked_candidates[:5],
                                })
                        print(f"    ✓ Match: {match.get('description', '')} (id {division_id})")
                        
                        # Get detailed cost data
                        cost_line = client.get_unit_costlines(
                            release_id=release_id,
                            catalog=catalog,
                            location_id=location_id,
                            labor_type=labor_type,
                            measurement_system=measurement_system,
                            division_code=division_id,
                        )
                        
                        if cost_line and "items" in cost_line:
                            for item in cost_line["items"]:
                                if item.get("id") == division_id:
                                    unit_cost = float(item.get("localizedCosts", {}).get("totalOpCost", 0.0) or 0.0)
                                    line_uom = item.get("unitOfMeasure", "")
                                    if unit_cost > 0 and division_code and not _id_matches_division(division_id, division_code):
                                        search_log.append({
                                            "material": material_name,
                                            "search_term": alt_term,
                                            "catalog": catalog,
                                            "division": alt_division,
                                            "status": "division_mismatch",
                                            "requested_division": division_code,
                                            "rsmeans_id": division_id,
                                            "rsmeans_description": item.get("description", ""),
                                        })
                                        unit_cost = 0.0
                                    if unit_cost > 0 and not _uom_compatible(unit, line_uom):
                                        # Reject: skip this candidate and keep searching.
                                        search_log.append({
                                            "material": material_name,
                                            "search_term": alt_term,
                                            "catalog": catalog,
                                            "division": alt_division,
                                            "status": "uom_incompatible",
                                            "unit_of_measure": line_uom,
                                            "requested_unit": unit,
                                            "rsmeans_id": division_id,
                                            "rsmeans_description": item.get("description", ""),
                                        })
                                        unit_cost = 0.0
                                    if unit_cost > 0:
                                        best_match = item
                                        best_cost = unit_cost * quantity
                                        best_catalog = catalog
                                        if _force_fallback_multi or match.get("is_fallback"):
                                            matched_term = "fallback_rsmeans_id"
                                            best_source = "rsmeans_fallback_id"
                                        else:
                                            matched_term = alt_term
                                            best_source = "rsmeans_search"
                                        
                                        status_msg = f"match_found"
                                        if alt_term != material_name:
                                            status_msg += f" (using '{alt_term}')"
                                            print(f"  -> Found match using alternative term: '{alt_term}' in catalog {catalog}")
                                        
                                        search_log.append({
                                            "material": material_name,
                                            "search_term": alt_term,
                                            "catalog": catalog,
                                            "division": alt_division,
                                            "status": status_msg,
                                            "unit_cost": unit_cost,
                                            "unit_of_measure": line_uom,
                                            "quantity": quantity,
                                            "total_cost": best_cost,
                                            "candidate_scores": ranked_candidates[:5],
                                        })
                                        break
                            
                            if best_match:
                                break  # Exit alternative terms loop
                    
                except Exception as e:
                    search_log.append({
                        "material": material_name,
                        "search_term": alt_term,
                        "catalog": catalog,
                        "status": "error",
                        "error": str(e)
                    })
        
        if best_match:
            _split = _split_total_by_bare(best_match, float(best_cost or 0.0))
            _qty = float(quantity or 0.0)
            _bare_unit = (float(_split["material"] or 0.0) / _qty) if _qty > 0.0 else 0.0
            _raw_comp = _extract_bare_components(best_match)
            _raw_unit_cost = float(_raw_comp.get("material", 0.0) or 0.0) + float(_raw_comp.get("labor", 0.0) or 0.0) + float(_raw_comp.get("equipment", 0.0) or 0.0)
            _raw_uom = _normalize_uom(best_match.get("unitOfMeasure", ""))
            if _raw_unit_cost <= 0.0:
                _raw_unit_cost = float(best_match.get("localizedCosts", {}).get("totalOpCost", 0.0) or 0.0)
            if not _raw_uom:
                _raw_uom = str(best_match.get("unitOfMeasure", "") or "")
            material_result = {
                **material,
                "catalog": best_catalog,
                "search_term_used": matched_term,
                "unit_cost": best_match.get("localizedCosts", {}).get("totalOpCost", 0.0),
                "total_cost": best_cost,
                "rsmeans_id": best_match.get("id", ""),
                "rsmeans_description": best_match.get("description", ""),
                "rsmeans_unit_of_measure": best_match.get("unitOfMeasure", ""),
                "source": best_source,
                "match_type": "fallback_id" if best_source == "rsmeans_fallback_id" else "closest_match",
                "chosen_source_type": "fallback" if best_source == "rsmeans_fallback_id" else "search",
                "bare_material_unit_cost": _bare_unit,
                "bare_material_unit_basis": best_match.get("unitOfMeasure", ""),
                "pricing_unit_cost_raw": _raw_unit_cost,
                "pricing_unit_uom_raw": _raw_uom,
                "pricing_unit_cost_effective": float(best_match.get("localizedCosts", {}).get("totalOpCost", 0.0) or 0.0),
                "pricing_unit_uom_effective": _raw_uom,
                "pricing_source": "rsmeans_direct" if float(best_match.get("localizedCosts", {}).get("totalOpCost", 0.0) or 0.0) > 0.0 else "unavailable",
            }
            material_result["total_material_cost"] = _split["material"]
            material_result["total_labor_cost"] = _split["labor"]
            material_result["total_equipment_cost"] = _split["equipment"]
            material_result["cost_component_source"] = _split["source"]
            all_results.append(material_result)
            _append_rsmeans_raw_log(material, best_match, best_catalog, str(best_source or "search"), matched_term)
            total_cost += best_cost
            total_material_cost_bare += _split["material"]
            total_labor_cost_bare += _split["labor"]
            total_equipment_cost_bare += _split["equipment"]
            if best_source == "rsmeans_fallback_id":
                fallback_count += 1
                warnings.append(
                    f"Used fallback RSMeans ID {best_match.get('id', '')} for '{material_name}' due to candidate score bounds"
                )
        else:
            fallback_id = _get_default_fallback_rsmeans_id(
                material_name,
                material.get("description", ""),
            )
            fallback_item = None
            fallback_catalog = None

            if fallback_id:
                for catalog in catalogs:
                    fallback_item = _lookup_cost_item_by_rsmeans_id(
                        client=client,
                        rsmeans_id=fallback_id,
                        catalog=catalog,
                        release_id=release_id,
                        location_id=location_id,
                        labor_type=labor_type,
                        measurement_system=measurement_system,
                    )
                    if fallback_item:
                        fallback_catalog = catalog
                        break

            if fallback_item:
                unit_cost = float(fallback_item.get("localizedCosts", {}).get("totalOpCost", 0.0) or 0.0)
                line_uom = fallback_item.get("unitOfMeasure", "")
                line_id = fallback_item.get("id", fallback_id)
                if unit_cost > 0 and division_code and not _id_matches_division(line_id, division_code):
                    warnings.append(
                        f"Final fallback RSMeans ID {fallback_id} for '{material_name}' "
                        f"resolved to id '{line_id}' outside division '{division_code}'. Skipping."
                    )
                    errors.append(
                        f"No division-compatible RSMeans match found for: {material_name} (division {division_code})"
                    )
                    search_log.append({
                        "material": material_name,
                        "status": "fallback_division_mismatch",
                        "fallback_rsmeans_id": fallback_id,
                        "catalog": fallback_catalog,
                        "requested_division": division_code,
                    })
                    continue
                if unit_cost > 0 and not _uom_compatible(unit, line_uom):
                    warnings.append(
                        f"Final fallback RSMeans ID {fallback_id} for '{material_name}' "
                        f"has UOM '{line_uom}' incompatible with requested unit '{unit}'. "
                        f"Skipping cost assignment to avoid unit-mismatch errors."
                    )
                    errors.append(
                        f"No UOM-compatible RSMeans match found for: {material_name} (requested {unit})"
                    )
                    search_log.append({
                        "material": material_name,
                        "status": "fallback_uom_incompatible",
                        "fallback_rsmeans_id": fallback_id,
                        "catalog": fallback_catalog,
                        "unit_of_measure": line_uom,
                        "requested_unit": unit,
                    })
                    continue
                total = unit_cost * quantity
                _split = _split_total_by_bare(fallback_item, total)
                all_results.append({
                    **material,
                    "catalog": fallback_catalog,
                    "search_term_used": "fallback_rsmeans_id",
                    "unit_cost": unit_cost,
                    "total_cost": total,
                    "total_material_cost": _split["material"],
                    "total_labor_cost": _split["labor"],
                    "total_equipment_cost": _split["equipment"],
                    "bare_material_unit_cost": (float(_split["material"] or 0.0) / float(quantity or 1.0)) if float(quantity or 0.0) > 0.0 else 0.0,
                    "bare_material_unit_basis": line_uom,
                    "cost_component_source": _split["source"],
                    "rsmeans_id": fallback_item.get("id", fallback_id),
                    "rsmeans_description": fallback_item.get("description", ""),
                    "rsmeans_unit_of_measure": line_uom,
                    "source": "rsmeans_fallback_id",
                    "match_type": "fallback_id",
                    "chosen_source_type": "fallback",
                })
                _append_rsmeans_raw_log(material, fallback_item, fallback_catalog, "fallback_rsmeans_id", "fallback_rsmeans_id")
                total_cost += total
                total_material_cost_bare += _split["material"]
                total_labor_cost_bare += _split["labor"]
                total_equipment_cost_bare += _split["equipment"]
                fallback_count += 1
                warning_message = (
                    f"Used fallback RSMeans ID {fallback_id} for '{material_name}' "
                    f"after no direct search match"
                )
                warnings.append(warning_message)
                search_log.append({
                    "material": material_name,
                    "status": "fallback_match",
                    "fallback_rsmeans_id": fallback_id,
                    "catalog": fallback_catalog,
                    "unit_cost": unit_cost,
                    "unit_of_measure": line_uom,
                    "quantity": quantity,
                    "total_cost": total,
                })
            else:
                errors.append(f"No RSMeans match found in any catalog for: {material_name}")
                search_log.append({
                    "material": material_name,
                    "status": "no_match",
                    "catalogs_searched": catalogs,
                    "alternatives_tried": len(search_alternatives),
                    "fallback_rsmeans_id": fallback_id,
                })
    
    return {
        "total_cost": total_cost,
        "total_material_cost": total_material_cost_bare,
        "total_labor_cost": total_labor_cost_bare,
        "total_equipment_cost": total_equipment_cost_bare,
        "materials": all_results,
        "errors": errors,
        "warnings": warnings,
        "fallback_count": fallback_count,
        "search_log": search_log,
        "catalogs_searched": catalogs
    }


def run_rsmeans_cost_lookup(
    materials: List[Dict[str, Any]],
    release_id: str = "2024-an",
    catalogs: Optional[List[str]] = None,
    location_id: str = "us-us-national",
    labor_type: str = "std",
    measurement_system: str = "imp",
    use_sandbox: bool = False,
    overhead_profit_percent: float = 0.0,
) -> Dict[str, Any]:
    """Run RSMeans lookup for provided materials and return summary/results."""
    load_dotenv()
    client_id = os.getenv("client_id")
    client_secret = os.getenv("client_secret")

    if not client_id or not client_secret:
        append_measure_summary_record(MEASURE_LOG_SLUG, {
            "status": "auth_error",
            "message": "RSMeans API credentials not found in environment",
        })
        return {
            "status": "auth_error",
            "message": "RSMeans API credentials not found in environment",
        }

    client = RSMeansAPIClient(client_id, client_secret, use_sandbox=use_sandbox)
    if not client.authenticate():
        append_measure_summary_record(MEASURE_LOG_SLUG, {
            "status": "auth_error",
            "message": "RSMeans authentication failed",
        })
        return {
            "status": "auth_error",
            "message": "RSMeans authentication failed",
        }

    results = search_materials_across_catalogs(
        materials=materials,
        client=client,
        catalogs=catalogs,
        release_id=release_id,
        location_id=location_id,
        labor_type=labor_type,
        measurement_system=measurement_system,
    )

    total_material_cost = float(results.get("total_material_cost", 0.0))
    total_labor_cost = float(results.get("total_labor_cost", 0.0))
    total_equipment_cost = float(results.get("total_equipment_cost", 0.0))
    total_bare_cost = total_material_cost + total_labor_cost + total_equipment_cost
    if total_bare_cost <= 0.0:
        total_bare_cost = float(results.get("total_cost", 0.0))
        total_material_cost = total_bare_cost
    # The per-line unit cost used during aggregation is the RSMeans
    # ``totalOpCost`` (Total Incl. O&P), so no additional overhead/profit
    # markup is applied here. The ``overhead_profit_percent`` argument is
    # retained for backward compatibility and is recorded in the summary
    # only; it does not alter the reported total.
    overhead_profit_cost = 0.0
    total_cost = total_bare_cost

