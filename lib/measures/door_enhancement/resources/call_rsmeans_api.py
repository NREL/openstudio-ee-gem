#!/usr/bin/env python
"""
RSMeans API helper for the door_enhancement measure.

This module is intentionally self-contained and local to door_enhancement.
It handles all RSMeans cost lookups for door components: whole doors, bottom
seals (brush weatherstrip, automatic door bottom, silicone smoke gasket), and
top/side seals (jamb weatherstrip, silicone smoke gasket).

This script can also be used as a standalone CLI tool to query RSMeans costs
from a saved OSM file (run ``python resources/call_rsmeans_api.py --help``).

Search behaviour (three-tier lookup):
1. If the caller provides an explicit RSMeans unit costline ID, that ID is
   resolved first via a direct catalog lookup before falling back to search.
2. A text search is attempted using progressive alternative terms generated by
   ``generate_search_term_alternatives``.  If the best candidate's clamped
   score is >= ``MIN_ACCEPTABLE_MATCH_SCORE`` (70.0), that candidate is used.
3. If no search succeeds or the score is too low, a hard-coded fallback ID
   from ``DOOR_FALLBACK_RSMEANS_IDS`` is resolved directly by catalog lookup.
"""

