# Minimum clamped match score [0-100] required to accept a search result.
# Scores below this trigger the fallback costline-ID lookup so that a
# low-confidence text match never silently produces wrong costs.
# Raised from 50 -> 70 because at 50 unrelated lines (e.g. a stainless-steel
# glass door costline) were scoring high enough to be accepted for a
# "wooden door" request, producing dramatically wrong costs (~$70k).
# Curated fallback IDs in DOOR_FALLBACK_RSMEANS_IDS are reliable, so it is
# safer to fall through to them when the search match is weak.
MIN_ACCEPTABLE_MATCH_SCORE = 70.0

